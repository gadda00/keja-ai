# ── TOC document template with body-page detection ─────────────────────────
class KejaDocTemplate(SimpleDocTemplate):
    """afterFlowable feeds TOCEntry tuples (with clickable key); the
    body-start marker lets the footer switch roman -> arabic numbering."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.body_start = None

    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))
        if getattr(flowable, "is_body_start", False):
            self.body_start = self.page


def _roman(n: int) -> str:
    vals = [(10, "x"), (9, "ix"), (5, "v"), (4, "iv"), (1, "i")]
    out = ""
    for v, sym in vals:
        while n >= v:
            out += sym
            n -= v
    return out


def make_painter(title: str, footer_left: str):
    """Header (title + accent rule) and footer (author + page number).
    Page 1 of the body PDF is the TOC -> roman; content -> arabic from 1."""
    def painter(canv, doc):
        canv.saveState()
        # header
        canv.setFont("FreeSerif", 7.5)
        canv.setFillColor(TEXT_MUTED)
        canv.drawString(MARGIN, PAGE_H - 0.55 * inch, title.upper())
        canv.setStrokeColor(ACCENT)
        canv.setLineWidth(1.2)
        canv.line(MARGIN, PAGE_H - 0.63 * inch, PAGE_W - MARGIN, PAGE_H - 0.63 * inch)
        # footer
        canv.setStrokeColor(BORDER)
        canv.setLineWidth(0.5)
        canv.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
        canv.setFont("FreeSerif", 7.5)
        canv.setFillColor(TEXT_MUTED)
        canv.drawString(MARGIN, 0.45 * inch, footer_left)
        body_start = doc.body_start
        if body_start is not None and doc.page >= body_start:
            label = str(doc.page - body_start + 1)
        else:
            label = _roman(doc.page)
        canv.drawRightString(PAGE_W - MARGIN, 0.45 * inch, label)
        canv.restoreState()
    return painter


# ── Building blocks ─────────────────────────────────────────────────────────
def heading(text: str, level: int = 0, chapter: str | None = None):
    """H1/H2/H3 with TOC bookmark. level 0 = chapter, 1 = section, 2 = sub."""
    style = S["h1"] if level == 0 else (S["h2"] if level == 1 else S["h3"])
    label = f"{chapter}&nbsp;&nbsp;{text}" if chapter else text
    key = "h_" + hashlib.md5(f"{level}-{chapter}-{text}".encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{label}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = min(level, 1)
    p.bookmark_text = f"{chapter} {text}" if chapter else text
    p.bookmark_key = key
    return p


def h1_block(text: str, chapter: str | None = None, first_para=None):
    """H1 + accent underline (+ optional first paragraph), orphan-protected."""
    items = [heading(text, 0, chapter),
             HRFlowable(width="100%", color=ACCENT, thickness=1.5,
                        spaceBefore=0, spaceAfter=10)]
    if first_para is not None:
        items.append(first_para)
    return [CondPageBreak(H1_ORPHAN), KeepTogether(items)]


def h2_block(text: str, first=None):
    items = [heading(text, 1)]
    if first is not None:
        items.append(first)
    return [CondPageBreak(70), KeepTogether(items)]


def _bind_dashes(t: str) -> str:
    """Closed em-dash style (word—word, Chicago): the dash lives inside a
    word unit so it can never start a line (ReportLab splits on \\xa0, so
    &nbsp; binding does not work)."""
    return t.replace(" — ", "—").replace(" —", "—").replace("— ", "—")


def body(text: str) -> Paragraph:
    return Paragraph(_bind_dashes(text), S["body"])


def lead(text: str) -> Paragraph:
    return Paragraph(_bind_dashes(text), S["lead"])


def bullets(items: list[str]) -> list:
    return [Paragraph("<bullet>&bull;</bullet>" + _bind_dashes(t), S["bullet"]) for t in items]


def callout_row(stats: list[tuple[str, str]]) -> Table:
    """Row of stat CalloutBoxes: [(big, label), ...] — data-to-ink rule."""
    n = len(stats)
    gap = 10
    w = (AVAIL_W - gap * (n - 1)) / n
    cells, widths = [], []
    for i, (big, label) in enumerate(stats):
        box = Table([[Paragraph(f"<b>{big}</b>", S["stat"])],
                     [Paragraph(label, S["stat_label"])]], colWidths=[w])
        box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), SECTION_BG),
            ("BOX", (0, 0), (-1, -1), 1, ACCENT),
            ("TOPPADDING", (0, 0), (-1, 0), 10),
            ("BOTTOMPADDING", (0, -1), (-1, -1), 9),
            ("TOPPADDING", (0, -1), (-1, -1), 2),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(box)
        widths.append(w)
        if i < n - 1:
            cells.append("")
            widths.append(gap)
    outer = Table([cells], colWidths=widths, hAlign="CENTER")
    outer.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return outer


def quote_box(text: str) -> Table:
    q = Table([[Paragraph(_bind_dashes(text), S["quote"])]], colWidths=[AVAIL_W * 0.92], hAlign="CENTER")
    q.setStyle(TableStyle([
        ("LINEBEFORE", (0, 0), (0, -1), 2.5, ACCENT),
        ("LEFTPADDING", (0, 0), (-1, -1), 14),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return q


def make_table(header: list[str], rows: list[list], ratios: list[float] | None = None,
               caption: str | None = None, font: float = 9.5, repeat: bool = True):
    """Paragraph-wrapped, centered, palette-coloured table (overflow-safe)."""
    ncols = len(header)
    if ratios is None:
        ratios = [1.0 / ncols] * ncols
    total = sum(ratios)
    widths = [r / total * AVAIL_W for r in ratios]
    assert abs(sum(widths) - AVAIL_W) < 1.0
    th = ParagraphStyle("th_x", parent=S["th"], fontSize=font)
    td = ParagraphStyle("td_x", parent=S["td"], fontSize=font)
    data = [[Paragraph(f"<b>{h}</b>", th) for h in header]]
    for row in rows:
        data.append([Paragraph(_bind_dashes(str(c)), td) for c in row])
    t = Table(data, colWidths=widths, hAlign="CENTER",
              repeatRows=1 if repeat else 0)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12), t]
    if caption:
        out += [Spacer(1, 4), Paragraph(caption, S["caption"])]
    out.append(Spacer(1, 10))
    return out


def code_block(text: str) -> Paragraph:
    return Paragraph(text.replace("\n", "<br/>").replace(" ", "&nbsp;"), S["code"])


def build_doc(story: list, out_path: str, title: str, subject: str,
              footer_left: str = "Keja AI · A Chacadom Investments venture"):
    """Standard build: TOC page -> PageBreak -> content. multiBuild for TOC."""
    toc = TableOfContents()
    toc.levelStyles = [S["toc0"], S["toc1"]]
    toc.dotsMinLevel = 0
    front = [Paragraph("<b>Table of Contents</b>", S["h1"]),
             HRFlowable(width="100%", color=ACCENT, thickness=1.5,
                        spaceBefore=0, spaceAfter=14),
             toc, PageBreak()]
    doc = KejaDocTemplate(out_path, pagesize=A4,
                          leftMargin=MARGIN, rightMargin=MARGIN,
                          topMargin=MARGIN, bottomMargin=MARGIN,
                          title=title, author="Z.ai", creator="Z.ai", subject=subject)
    painter = make_painter(title, footer_left)
    doc.multiBuild(front + story, onFirstPage=painter, onLaterPages=painter)
    return out_path


def mark_body_start(story: list):
    """Attach the body-start flag to the first heading (recursing into
    KeepTogether wrappers) so the footer can switch roman -> arabic."""
    def find(fl):
        if hasattr(fl, "bookmark_name"):
            return fl
        for inner in getattr(fl, "_content", []):
            found = find(inner)
            if found is not None:
                return found
        return None

    for fl in story:
        if isinstance(fl, CondPageBreak):
            continue
        target = find(fl)
        if target is not None:
            target.is_body_start = True
            return


