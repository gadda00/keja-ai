def merge_cover(cover_pdf: str, body_pdf: str, out_pdf: str, title: str,
                subject: str):
    from pypdf import PdfReader, PdfWriter
    A4_W, A4_H = 595.28, 841.89

    def norm(page):
        w, h = float(page.mediabox.width), float(page.mediabox.height)
        if abs(w - A4_W) > 0.3 or abs(h - A4_H) > 0.3:
            page.scale_to(A4_W, A4_H)
        return page

    writer = PdfWriter()
    writer.add_page(norm(PdfReader(cover_pdf).pages[0]))
    for page in PdfReader(body_pdf).pages:
        writer.add_page(norm(page))
    writer.add_metadata({"/Title": title, "/Author": "Z.ai", "/Creator": "Z.ai",
                         "/Subject": subject})
    with open(out_pdf, "wb") as f:
        writer.write(f)
    return out_pdf
