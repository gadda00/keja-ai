#!/usr/bin/env node
/**
 * Data dictionary generator — automated data governance.
 *
 * Review feedback: "Keja needs a data dictionary, source contracts, freshness
 * standards, lineage." The first artefact is this generator: it walks the
 * TypeScript source of the demo datasets, extracts every exported interface
 * and type alias with their field signatures, and emits docs/DATA_DICTIONARY.md.
 * Run locally or in CI; the doc is committed so it never rots silently.
 *
 * Usage: node scripts/generate-data-dictionary.mjs
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = [
  { path: 'src/data/properties.ts', note: 'Marketplace listing inventory (seed stock).' },
  { path: 'src/data/claims.ts', note: 'Capability claims register (the truth layer).' },
  { path: 'src/data/tokenize.ts', note: 'Tokenization demo assets, ledger and portfolio.' },
  { path: 'src/data/articles.ts', note: 'Insights/editorial content.' },
  { path: 'src/data/auto-listings.json', note: 'Auto-Pilot ingested listings (machine-screened).' },
]

/** Extract `export interface X { ... }` blocks with their field lines. */
function extractInterfaces(src) {
  const out = []
  const re = /export interface (\w+)(?: extends (\w+))?\s*\{/g
  let m
  while ((m = re.exec(src))) {
    const name = m[1]
    const ext = m[2]
    const start = m.index + m[0].length
    let depth = 1
    let i = start
    while (i < src.length && depth > 0) {
      if (src[i] === '{') depth++
      else if (src[i] === '}') depth--
      i++
    }
    const body = src.slice(start, i - 1)
    const fields = body
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith('//') && !l.startsWith('*') && !l.startsWith('/*'))
    out.push({ name, ext, fields })
  }
  return out
}

function extractTypeAliases(src) {
  const out = []
  const re = /export type (\w+)(<[^>]*>)?\s*=\s*([^;]+);/g
  let m
  while ((m = re.exec(src))) {
    out.push({ name: m[1], def: m[3].replace(/\s+/g, ' ').trim() })
  }
  return out
}

function extractJsonShape(path) {
  const data = JSON.parse(readFileSync(resolve(ROOT, path), 'utf8'))
  const lines = Object.entries(data).map(([k, v]) => {
    const kind = Array.isArray(v) ? `array (${v.length} items)` : typeof v
    return `- **${k}** — \`${kind}\``
  })
  const sample = Array.isArray(data.listings?.[0] ?? null) ? null : data.listings?.[0]
  if (sample) {
    lines.push('', 'First listing record fields:')
    for (const [k, v] of Object.entries(sample)) {
      lines.push(`  - **${k}** — \`${typeof v}\`${typeof v === 'number' ? ` (e.g. ${v})` : ''}`)
    }
  }
  return lines
}

const today = new Date().toISOString().slice(0, 10)
let md = `# Data Dictionary — generated ${today}

> AUTO-GENERATED by \`scripts/generate-data-dictionary.mjs\` — do not edit by hand.
> Run \`node scripts/generate-data-dictionary.mjs\` after changing any dataset.

Purpose: every dataset in this demo is documented with its fields so future
contributors (and the Phase-2 backend migration) know exactly what each store
holds. Derived from the TypeScript source of truth.

`

for (const s of SOURCES) {
  if (!existsSync(resolve(ROOT, s.path))) continue
  md += `\n## \`${s.path}\`\n\n${s.note}\n\n`
  if (s.path.endsWith('.json')) {
    md += extractJsonShape(s.path).join('\n') + '\n'
    continue
  }
  const src = readFileSync(resolve(ROOT, s.path), 'utf8')
  const interfaces = extractInterfaces(src)
  const aliases = extractTypeAliases(src)
  if (!interfaces.length && !aliases.length) {
    md += '_No exported interfaces/type aliases found._\n'
    continue
  }
  for (const a of aliases) {
    md += `- **${a.name}** = \`${a.def}\`\n`
  }
  if (aliases.length) md += '\n'
  for (const i of interfaces) {
    md += `### \`${i.name}\`${i.ext ? ` extends \`${i.ext}\`` : ''}\n\n`
    for (const f of i.fields) md += `- ${f}\n`
    md += '\n'
  }
}

const outDir = resolve(ROOT, 'docs')
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })
writeFileSync(resolve(outDir, 'DATA_DICTIONARY.md'), md, 'utf8')
console.log(`[data-dictionary] wrote docs/DATA_DICTIONARY.md (${md.split('\n').length} lines)`)
